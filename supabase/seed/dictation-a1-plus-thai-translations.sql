updated AS (
  UPDATE public.dictation_words AS d
  SET thai_translation = t.thai_translation
  FROM translations AS t
  WHERE d.level_code = 'A1+'
    AND d.is_active = true
    AND lower(trim(d.word)) = lower(t.word)
  RETURNING d.id
)
SELECT
  (SELECT COUNT(*) FROM translations) AS translations_in_script,
  (SELECT COUNT(*) FROM updated) AS database_rows_updated,
  (
    SELECT COUNT(*)
    FROM public.dictation_words
    WHERE level_code = 'A1+'
      AND is_active = true
      AND NULLIF(trim(thai_translation), '') IS NULL
  ) AS a1_plus_words_still_missing_translation;

-- List any remaining A1+ words that need a translation.
SELECT word
FROM public.dictation_words
WHERE level_code = 'A1+'
  AND is_active = true
  AND NULLIF(trim(thai_translation), '') IS NULL
ORDER BY word;
